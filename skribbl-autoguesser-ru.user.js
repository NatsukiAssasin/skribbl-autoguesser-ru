async function exportNewWords() {
    const old = new Set(RU_WORDS);
    if (ENABLE_ENGLISH) {
        (await fetchWords("https://raw.githubusercontent.com/zkisaboss/skribbl-autoguesser/main/wordlist.txt")).forEach(w => old.add(w));
    }
    const data = correctAnswers.filter(word => !old.has(word));
    if (!data.length) return;

    const url = URL.createObjectURL(new Blob([data.join('\n')], { type: "text/plain" }));
    try {
        const anchor = Object.assign(document.createElement('a'), { href: url, download: "newWords.txt" });
        document.body.appendChild(anchor);
        anchor.click();
        anchor.remove();
    } finally {
        setTimeout(() => URL.revokeObjectURL(url), 0);
    }
}

